-- RecipeRadar migration 001: relational schema (PostgreSQL 14+).
-- Tables, keys, constraints, indexes, integrity triggers, and views.
-- Functions/procedures are in 002; full-text search in 003; roles/RLS in 004.

CREATE TABLE users (
  user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 100),
  email TEXT NOT NULL
    CHECK (char_length(email) BETWEEN 3 AND 255 AND email = btrim(email) AND position('@' IN email) > 1),
  password_hash TEXT NOT NULL CHECK (char_length(password_hash) BETWEEN 1 AND 255),
  role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
  age INTEGER CHECK (age BETWEEN 1 AND 120),
  diet_goal TEXT NOT NULL DEFAULT 'Balanced'
    CHECK (diet_goal IN ('Balanced', 'Vegan', 'Vegetarian', 'High protein')),
  daily_calorie_target INTEGER NOT NULL DEFAULT 2000 CHECK (daily_calorie_target BETWEEN 800 AND 6000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_lower_key ON users (lower(email));

CREATE TABLE allergens (
  allergen_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 50),
  severity TEXT NOT NULL DEFAULT 'High' CHECK (severity IN ('Low', 'Moderate', 'High', 'Severe'))
);
CREATE UNIQUE INDEX allergens_name_lower_key ON allergens (lower(name));

CREATE TABLE user_allergens (
  user_id INTEGER NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
  allergen_id INTEGER NOT NULL REFERENCES allergens (allergen_id) ON DELETE RESTRICT,
  PRIMARY KEY (user_id, allergen_id)
);

CREATE TABLE cuisines (
  cuisine_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 50)
);
CREATE UNIQUE INDEX cuisines_name_lower_key ON cuisines (lower(name));

CREATE TABLE dietary_types (
  diet_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 50)
);
CREATE UNIQUE INDEX dietary_types_name_lower_key ON dietary_types (lower(name));

CREATE TABLE ingredients (
  ingredient_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 100),
  category TEXT CHECK (char_length(category) <= 50),
  unit TEXT NOT NULL DEFAULT 'g' CHECK (char_length(btrim(unit)) BETWEEN 1 AND 20),
  is_common_allergen BOOLEAN NOT NULL DEFAULT false,
  flavor TEXT NOT NULL DEFAULT 'savory' CHECK (char_length(btrim(flavor)) BETWEEN 1 AND 100)
);
CREATE UNIQUE INDEX ingredients_name_lower_key ON ingredients (lower(name));

-- Identifies WHICH allergens each ingredient contains (many-to-many).
CREATE TABLE ingredient_allergens (
  ingredient_id INTEGER NOT NULL REFERENCES ingredients (ingredient_id) ON DELETE CASCADE,
  allergen_id INTEGER NOT NULL REFERENCES allergens (allergen_id) ON DELETE RESTRICT,
  PRIMARY KEY (ingredient_id, allergen_id)
);

CREATE TABLE recipes (
  recipe_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 200),
  description TEXT CHECK (char_length(description) <= 2000),
  instructions JSONB NOT NULL
    CHECK (jsonb_typeof(instructions) = 'array' AND jsonb_array_length(instructions) > 0),
  prep_time_minutes INTEGER NOT NULL DEFAULT 10 CHECK (prep_time_minutes BETWEEN 0 AND 10080),
  cook_time_minutes INTEGER NOT NULL DEFAULT 15 CHECK (cook_time_minutes BETWEEN 0 AND 10080),
  servings INTEGER NOT NULL CHECK (servings BETWEEN 1 AND 1000),
  calories_per_serving NUMERIC(8, 2) NOT NULL CHECK (calories_per_serving > 0),
  protein_g NUMERIC(6, 2) NOT NULL DEFAULT 0 CHECK (protein_g >= 0),
  carbs_g NUMERIC(6, 2) NOT NULL DEFAULT 0 CHECK (carbs_g >= 0),
  fat_g NUMERIC(6, 2) NOT NULL DEFAULT 0 CHECK (fat_g >= 0),
  avg_rating NUMERIC(3, 2) NOT NULL DEFAULT 0 CHECK (avg_rating BETWEEN 0 AND 5),
  total_views INTEGER NOT NULL DEFAULT 0 CHECK (total_views >= 0),
  cuisine_id INTEGER NOT NULL REFERENCES cuisines (cuisine_id) ON DELETE RESTRICT,
  diet_id INTEGER NOT NULL REFERENCES dietary_types (diet_id) ON DELETE RESTRICT,
  created_by INTEGER NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,
  -- New recipes are unapproved until an administrator reviews them.
  is_approved BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  image TEXT,
  meal_type TEXT NOT NULL DEFAULT 'Lunch' CHECK (meal_type IN ('Breakfast', 'Lunch', 'Dinner')),
  flavor TEXT NOT NULL DEFAULT 'savory' CHECK (char_length(btrim(flavor)) BETWEEN 1 AND 100)
);

CREATE TABLE recipe_ingredients (
  recipe_id INTEGER NOT NULL REFERENCES recipes (recipe_id) ON DELETE CASCADE,
  ingredient_id INTEGER NOT NULL REFERENCES ingredients (ingredient_id) ON DELETE RESTRICT,
  quantity NUMERIC(8, 2) NOT NULL CHECK (quantity > 0),
  unit TEXT NOT NULL DEFAULT 'g' CHECK (char_length(btrim(unit)) BETWEEN 1 AND 20),
  PRIMARY KEY (recipe_id, ingredient_id)
);

CREATE TABLE ratings (
  user_id INTEGER NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
  recipe_id INTEGER NOT NULL REFERENCES recipes (recipe_id) ON DELETE CASCADE,
  rating_value INTEGER NOT NULL CHECK (rating_value BETWEEN 1 AND 5),
  review_text TEXT CHECK (char_length(review_text) <= 2000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, recipe_id)
);

CREATE TABLE favorites (
  user_id INTEGER NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
  recipe_id INTEGER NOT NULL REFERENCES recipes (recipe_id) ON DELETE CASCADE,
  saved_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, recipe_id)
);

CREATE TABLE meal_plans (
  plan_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
  plan_name TEXT NOT NULL CHECK (char_length(btrim(plan_name)) BETWEEN 1 AND 100),
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (end_date >= start_date)
);

CREATE TABLE meal_plan_recipes (
  plan_id INTEGER NOT NULL REFERENCES meal_plans (plan_id) ON DELETE CASCADE,
  recipe_id INTEGER NOT NULL REFERENCES recipes (recipe_id) ON DELETE RESTRICT,
  meal_date DATE NOT NULL,
  meal_type TEXT NOT NULL CHECK (meal_type IN ('Breakfast', 'Lunch', 'Dinner')),
  servings_planned NUMERIC(6, 2) NOT NULL DEFAULT 1 CHECK (servings_planned > 0 AND servings_planned <= 1000),
  -- One recipe per date/meal slot. A recipe can repeat on different days.
  PRIMARY KEY (plan_id, meal_date, meal_type)
);

CREATE TABLE substitutions (
  ingredient_id_from INTEGER NOT NULL REFERENCES ingredients (ingredient_id) ON DELETE CASCADE,
  ingredient_id_to INTEGER NOT NULL REFERENCES ingredients (ingredient_id) ON DELETE CASCADE,
  similarity_score NUMERIC(3, 2) NOT NULL CHECK (similarity_score BETWEEN 0 AND 1),
  PRIMARY KEY (ingredient_id_from, ingredient_id_to),
  CHECK (ingredient_id_from <> ingredient_id_to)
);

CREATE TABLE sessions (
  token TEXT PRIMARY KEY CHECK (token ~ '^[0-9a-f]{64}$'),
  user_id INTEGER NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
  expires_at BIGINT NOT NULL CHECK (expires_at > 0)
);

-- Durable transactional outbox bridging recipe changes to the vector index.
-- recipe_id intentionally has no FK so delete tombstones survive row deletion.
CREATE TABLE vector_sync_outbox (
  outbox_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipe_id INTEGER NOT NULL,
  operation TEXT NOT NULL CHECK (operation IN ('upsert', 'delete')),
  payload JSONB,
  attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  last_error TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (recipe_id, operation)
);

-- Vector store inside PostgreSQL: one normalised 128-d embedding per approved recipe.
CREATE TABLE vector_documents (
  recipe_id INTEGER PRIMARY KEY REFERENCES recipes (recipe_id) ON DELETE CASCADE,
  embedding DOUBLE PRECISION[] NOT NULL CHECK (array_ndims(embedding) = 1 AND cardinality(embedding) = 128),
  payload JSONB NOT NULL CHECK (jsonb_typeof(payload) = 'object'),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Trigger-written audit trail of privileged changes (role grants, recipe moderation).
CREATE TABLE audit_log (
  audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_name TEXT NOT NULL,
  record_id INTEGER NOT NULL,
  action TEXT NOT NULL,
  old_value TEXT,
  new_value TEXT,
  actor_user_id INTEGER,
  db_role TEXT NOT NULL DEFAULT session_user,
  changed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_user_allergen_reverse ON user_allergens (allergen_id);
CREATE INDEX idx_ingredient_allergen_reverse ON ingredient_allergens (allergen_id);
CREATE INDEX idx_recipe_ingredient ON recipe_ingredients (ingredient_id);
CREATE INDEX idx_recipes_creator ON recipes (created_by);
CREATE INDEX idx_recipes_cuisine ON recipes (cuisine_id);
CREATE INDEX idx_recipes_diet ON recipes (diet_id, is_approved);
CREATE INDEX idx_rating_recipe ON ratings (recipe_id);
CREATE INDEX idx_favorites_recipe ON favorites (recipe_id);
CREATE INDEX idx_plan_user ON meal_plans (user_id, start_date);
CREATE INDEX idx_plan_recipe ON meal_plan_recipes (recipe_id);
CREATE INDEX idx_substitution_target ON substitutions (ingredient_id_to);
CREATE INDEX idx_session_user ON sessions (user_id);
CREATE INDEX idx_session_expiry ON sessions (expires_at);
CREATE INDEX idx_vector_outbox_created ON vector_sync_outbox (created_at);
CREATE INDEX idx_vector_payload_diet ON vector_documents ((payload ->> 'diet'));
CREATE INDEX idx_audit_table_record ON audit_log (table_name, record_id);

-- ---------------------------------------------------------------------------
-- Integrity triggers (PL/pgSQL). SECURITY DEFINER where a trigger must write or
-- read rows that the invoking low-privilege role cannot touch directly.
-- ---------------------------------------------------------------------------

-- Keep recipes.avg_rating derived from ratings (INSERT/UPDATE/DELETE).
CREATE FUNCTION trg_refresh_avg_rating() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
  IF TG_OP IN ('UPDATE', 'DELETE') THEN
    UPDATE recipes SET avg_rating = COALESCE(
      (SELECT round(avg(rating_value), 2) FROM ratings WHERE recipe_id = OLD.recipe_id), 0)
    WHERE recipe_id = OLD.recipe_id;
  END IF;
  IF TG_OP IN ('INSERT', 'UPDATE') THEN
    UPDATE recipes SET avg_rating = COALESCE(
      (SELECT round(avg(rating_value), 2) FROM ratings WHERE recipe_id = NEW.recipe_id), 0)
    WHERE recipe_id = NEW.recipe_id;
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER ratings_refresh_avg
AFTER INSERT OR UPDATE OR DELETE ON ratings
FOR EACH ROW EXECUTE FUNCTION trg_refresh_avg_rating();

-- Reject hand-edited avg_rating values.
CREATE FUNCTION trg_guard_avg_rating() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.avg_rating <> 0 THEN
      RAISE EXCEPTION 'avg_rating is maintained by rating triggers' USING ERRCODE = 'check_violation';
    END IF;
  ELSIF NEW.avg_rating IS DISTINCT FROM COALESCE(
      (SELECT round(avg(rating_value), 2) FROM ratings WHERE recipe_id = NEW.recipe_id), 0) THEN
    RAISE EXCEPTION 'avg_rating is maintained by rating triggers' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER recipes_guard_avg_insert BEFORE INSERT ON recipes
FOR EACH ROW EXECUTE FUNCTION trg_guard_avg_rating();
CREATE TRIGGER recipes_guard_avg_update BEFORE UPDATE OF avg_rating ON recipes
FOR EACH ROW WHEN (NEW.avg_rating IS DISTINCT FROM OLD.avg_rating)
EXECUTE FUNCTION trg_guard_avg_rating();

-- Keep ingredients.is_common_allergen derived from ingredient_allergens.
CREATE FUNCTION trg_refresh_allergen_flag() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
  IF TG_OP IN ('UPDATE', 'DELETE') THEN
    UPDATE ingredients SET is_common_allergen =
      EXISTS (SELECT 1 FROM ingredient_allergens WHERE ingredient_id = OLD.ingredient_id)
    WHERE ingredient_id = OLD.ingredient_id;
  END IF;
  IF TG_OP IN ('INSERT', 'UPDATE') THEN
    UPDATE ingredients SET is_common_allergen = true WHERE ingredient_id = NEW.ingredient_id;
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER ingredient_allergens_refresh_flag
AFTER INSERT OR UPDATE OR DELETE ON ingredient_allergens
FOR EACH ROW EXECUTE FUNCTION trg_refresh_allergen_flag();

CREATE FUNCTION trg_guard_allergen_flag() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.is_common_allergen THEN
      RAISE EXCEPTION 'Create ingredient first, then add its allergen mappings' USING ERRCODE = 'check_violation';
    END IF;
  ELSIF NEW.is_common_allergen <> EXISTS (
      SELECT 1 FROM ingredient_allergens WHERE ingredient_id = NEW.ingredient_id) THEN
    RAISE EXCEPTION 'is_common_allergen is maintained by allergen mappings' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER ingredients_guard_flag_insert BEFORE INSERT ON ingredients
FOR EACH ROW EXECUTE FUNCTION trg_guard_allergen_flag();
CREATE TRIGGER ingredients_guard_flag_update BEFORE UPDATE OF is_common_allergen ON ingredients
FOR EACH ROW WHEN (NEW.is_common_allergen IS DISTINCT FROM OLD.is_common_allergen)
EXECUTE FUNCTION trg_guard_allergen_flag();

-- A meal must fall inside its plan's date range; plans cannot shrink past their meals.
CREATE FUNCTION trg_check_meal_date() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM meal_plans
                 WHERE plan_id = NEW.plan_id AND NEW.meal_date BETWEEN start_date AND end_date) THEN
    RAISE EXCEPTION 'Meal date must be within its plan date range' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER meal_plan_recipes_date_check
BEFORE INSERT OR UPDATE OF plan_id, meal_date ON meal_plan_recipes
FOR EACH ROW EXECUTE FUNCTION trg_check_meal_date();

CREATE FUNCTION trg_check_plan_range() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM meal_plan_recipes
             WHERE plan_id = OLD.plan_id AND meal_date NOT BETWEEN NEW.start_date AND NEW.end_date) THEN
    RAISE EXCEPTION 'Plan dates cannot exclude existing meals' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER meal_plans_range_check BEFORE UPDATE OF start_date, end_date ON meal_plans
FOR EACH ROW EXECUTE FUNCTION trg_check_plan_range();

-- Every cooking step must be a nonempty string of at most 2000 characters.
CREATE FUNCTION trg_check_recipe_steps() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM jsonb_array_elements(NEW.instructions) AS step(value)
    WHERE jsonb_typeof(step.value) <> 'string'
       OR char_length(btrim(step.value #>> '{}')) = 0
       OR char_length(step.value #>> '{}') > 2000) THEN
    RAISE EXCEPTION 'Instructions must contain nonempty text steps of at most 2000 characters'
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER recipes_check_steps BEFORE INSERT OR UPDATE OF instructions ON recipes
FOR EACH ROW EXECUTE FUNCTION trg_check_recipe_steps();

-- The last administrator can be neither demoted nor deleted.
CREATE FUNCTION trg_protect_last_admin() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
  IF OLD.role = 'admin' AND (TG_OP = 'DELETE' OR NEW.role <> 'admin')
     AND (SELECT count(*) FROM users WHERE role = 'admin') <= 1 THEN
    RAISE EXCEPTION 'Cannot remove the last administrator' USING ERRCODE = 'check_violation';
  END IF;
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $$;
CREATE TRIGGER users_protect_last_admin BEFORE UPDATE OF role OR DELETE ON users
FOR EACH ROW EXECUTE FUNCTION trg_protect_last_admin();

-- Audit privileged changes. actor comes from the transaction-local setting rr.user_id.
CREATE FUNCTION trg_audit_privileged() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE actor INTEGER := nullif(current_setting('rr.user_id', true), '')::integer;
BEGIN
  IF TG_TABLE_NAME = 'users' THEN
    INSERT INTO audit_log (table_name, record_id, action, old_value, new_value, actor_user_id)
    VALUES ('users', NEW.user_id, 'role_change', OLD.role, NEW.role, actor);
  ELSE
    INSERT INTO audit_log (table_name, record_id, action, old_value, new_value, actor_user_id)
    VALUES ('recipes', NEW.recipe_id, 'moderation', OLD.is_approved::text, NEW.is_approved::text, actor);
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER users_audit_role AFTER UPDATE OF role ON users
FOR EACH ROW WHEN (OLD.role IS DISTINCT FROM NEW.role) EXECUTE FUNCTION trg_audit_privileged();
CREATE TRIGGER recipes_audit_moderation AFTER UPDATE OF is_approved ON recipes
FOR EACH ROW WHEN (OLD.is_approved IS DISTINCT FROM NEW.is_approved) EXECUTE FUNCTION trg_audit_privileged();

-- Identity of the signed-in user, set per transaction by the application (SET LOCAL rr.user_id).
CREATE FUNCTION rr_uid() RETURNS INTEGER
LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('rr.user_id', true), '')::integer $$;

-- ---------------------------------------------------------------------------
-- Views: shared reporting logic for the application and the viva.
-- ---------------------------------------------------------------------------

-- The signed-in user's own profile. Runs with the owner's rights (no security_invoker) so
-- low-privilege roles can read their own row without any grant on other users' columns.
CREATE VIEW my_profile AS
SELECT user_id, name, email, role, age, diet_goal, daily_calorie_target, created_at
FROM users
WHERE user_id = rr_uid();

CREATE VIEW recipe_allergen_details AS
SELECT DISTINCT ri.recipe_id, i.ingredient_id, i.name AS ingredient, a.allergen_id, a.name AS allergen
FROM recipe_ingredients ri
JOIN ingredients i USING (ingredient_id)
JOIN ingredient_allergens ia USING (ingredient_id)
JOIN allergens a USING (allergen_id);

CREATE VIEW meal_plan_daily_nutrition AS
SELECT p.plan_id, p.user_id, m.meal_date,
  round(sum(r.calories_per_serving * m.servings_planned), 2) AS calories,
  round(sum(r.protein_g * m.servings_planned), 2) AS protein_g,
  round(sum(r.carbs_g * m.servings_planned), 2) AS carbs_g,
  round(sum(r.fat_g * m.servings_planned), 2) AS fat_g
FROM meal_plans p
JOIN meal_plan_recipes m USING (plan_id)
JOIN recipes r USING (recipe_id)
GROUP BY p.plan_id, p.user_id, m.meal_date;

-- Quantities are for a full recipe; scale by planned servings / base servings.
CREATE VIEW meal_plan_shopping_list AS
SELECT p.plan_id, p.user_id, i.ingredient_id, i.name AS ingredient, ri.unit,
  round(sum(ri.quantity * m.servings_planned / r.servings), 2) AS quantity
FROM meal_plans p
JOIN meal_plan_recipes m USING (plan_id)
JOIN recipes r USING (recipe_id)
JOIN recipe_ingredients ri USING (recipe_id)
JOIN ingredients i USING (ingredient_id)
GROUP BY p.plan_id, p.user_id, i.ingredient_id, i.name, ri.unit;
